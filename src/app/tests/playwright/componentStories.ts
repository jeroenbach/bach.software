/**
 * The Storybook stories captured by `components.spec.ts`, by story id.
 *
 * A story id is `<sidebar title>--<story name>` in kebab case. The capture is
 * named after the id without its `components-` or `elements-` sidebar prefix.
 */
export interface StoryRegistration {
  id: string
  /**
   * Stories that render outside the per-theme wrapper (dialogs, teleported bars)
   * are captured once per listed theme instead of both themes side by side.
   */
  themes?: ('light' | 'dark')[]
  /** The iframe has no viewport toolbar, so a story that needs a width states it. */
  viewport?: { width: number, height: number }
}

