import type { Meta, StoryObj } from '@storybook/vue3-vite';
import { provide } from 'vue';

import MessageBar from './MessageBar.vue';
import MessageBarOutlet from './MessageBarOutlet.vue';
import { messageBarRegistryKey } from './messageBarRegistry';

// Bars teleport into the outlet by name. The theme decorator renders every story
// twice (light and dark), so each instance provides its own registry with unique
// outlet names; otherwise both copies would teleport into the first outlet.
let outletInstance = 0;
function provideIsolatedRegistry() {
  outletInstance += 1;
  const outlets = {
    main: `story-${outletInstance}`,
    sticky: `story-${outletInstance}-sticky`,
    fixed: `story-${outletInstance}-fixed`,
  };
  provide(messageBarRegistryKey, {
    currentOutlets: () => outlets,
    registerOutlet: () => outlets,
  });
}

const meta = {
  title: 'Components/MessageBarOutlet',
  component: MessageBarOutlet,
  render: args => ({
    components: { MessageBarOutlet },
    setup() {
      provideIsolatedRegistry();
      return { args };
    },
    template: `<MessageBarOutlet v-bind="args" />`,
  }),
} satisfies Meta<typeof MessageBarOutlet>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = {
  render: args => ({
    components: { MessageBarOutlet, MessageBar },
    setup() {
      provideIsolatedRegistry();
      return { args };
    },
    template: `<MessageBarOutlet v-bind="args" />
      <MessageBar severity="success" description="Copied to clipboard!" />`,
  }),
};

export const Empty: Story = {};

export const StackedMessages: Story = {
  render: args => ({
    components: { MessageBarOutlet, MessageBar },
    setup() {
      provideIsolatedRegistry();
      return { args };
    },
    template: `<MessageBarOutlet v-bind="args" />
      <MessageBar severity="success" description="Copied to clipboard!" />
      <MessageBar severity="error" description="The page statistics could not be loaded." />
      <MessageBar severity="warning" description="This translation was generated by AI." />
      <MessageBar severity="info" description="A new version of this page is available." />`,
  }),
};
